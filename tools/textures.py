"""Builds game/textures/ from ambientCG (CC0) textures and writes game/src/View/TextureSet.g.cs.

The source textures are ambientCG's (https://ambientcg.com, CC0 1.0). This script reads them
from a local copy of github.com/PatrickJnr/cc0-texture-pack (Source 2 .vtex_c files), decoded
with tools/vtex.py, so it needs that checkout: python3 tools/textures.py <pack>/textures

Ground textures are shrunk to 256x256: low resolution on purpose, for the old-school look.
"""
import os, sys, glob
sys.path.insert(0, os.path.dirname(__file__))
import vtex
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..')
OUT = os.path.join(ROOT, 'game', 'textures')

# theme -> (shore, low ground, high ground, cliff rock), as ambientCG asset ids.
GROUND = {
    'temperate': ('Ground044', 'Terrain002', 'Ground024', 'Rock030'),
    'desert':    ('Ground026', 'Ground025', 'Ground028', 'Rock022'),
    'arctic':    ('Ice004', 'Rock026', 'Gravel023', 'Rock027'),
    'lava':      ('Rocks016', 'Gravel024', 'Rock014', 'Rock033'),
}
SIZE = 256

def find(src, asset):
    hits = glob.glob(os.path.join(src, '*', asset.lower() + '_color_*.vtex_c'))
    if not hits: raise SystemExit(f'{asset} not found under {src}')
    return hits[0]

def load(src, asset, size=SIZE):
    return vtex.decode(find(src, asset), size * 2).resize((size, size), Image.LANCZOS)

def average(im):
    px = im.resize((1, 1), Image.BOX).getpixel((0, 0))
    return tuple(round(c / 255, 4) for c in px)

def main(src):
    os.makedirs(OUT, exist_ok=True)
    lines = []
    for theme, assets in GROUND.items():
        avgs = []
        for slot, asset in zip(('shore', 'low', 'high', 'rock'), assets):
            im = load(src, asset)
            im.save(os.path.join(OUT, f'{theme}_{slot}.png'))
            avgs.append(average(im))
        a = ', '.join(f'new Color({r}f, {g}f, {b}f)' for r, g, b in avgs)
        lines.append(f'        ["{theme}"] = new[] {{ {a} }},')

    # Hull detail, one RGB texture: R = plating (panels and rivets), G = paint wear
    # (where the paint has chipped through to rust), B = rust/grime streaks.
    plates = load(src, 'MetalPlates001').convert('L')
    paint = load(src, 'PaintedMetal010')
    rust = load(src, 'Rust004').convert('L')
    wear = Image.new('L', paint.size)
    wp = wear.load(); pp = paint.load()
    for y in range(paint.size[1]):
        for x in range(paint.size[0]):
            r, g, b = pp[x, y]
            wp[x, y] = 255 if r > b + 30 and r > 70 else 0
    Image.merge('RGB', (plates, wear, rust)).save(os.path.join(OUT, 'hull_detail.png'))
    hull = average(Image.merge('RGB', (plates, wear, rust)))

    cs = os.path.join(ROOT, 'game', 'src', 'View', 'TextureSet.g.cs')
    with open(cs, 'w') as f:
        f.write('// Generated by tools/textures.py. Don\'t edit by hand.\n')
        f.write('using System.Collections.Generic;\nusing Godot;\n\nnamespace ContingencyZero.Game.View;\n\n')
        f.write('/// <summary>Average colour of each ground texture (shore, low, high, rock) per theme, and of the hull detail map.</summary>\n')
        f.write('public static class TextureSet\n{\n')
        f.write('    public static readonly Dictionary<string, Color[]> GroundAverages = new()\n    {\n')
        f.write('\n'.join(lines) + '\n    };\n')
        f.write(f'    public static readonly Color HullAverage = new({hull[0]}f, {hull[1]}f, {hull[2]}f);\n}}\n')
    print('wrote', OUT, cs)

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '/tmp/claude-0/tex/cc0-texture-pack/textures')
